const assert = require("assert");
const fs = require("fs");

const app = fs.readFileSync(require.resolve("../js/app.js"), "utf8");
const shopController = fs.readFileSync(require.resolve("../js/shop/shop-controller.js"), "utf8");
const shopView = fs.readFileSync(require.resolve("../js/shop/shop-view.js"), "utf8");
const settingsController = fs.readFileSync(require.resolve("../js/settings/settings-controller.js"), "utf8");
const settingsView = fs.readFileSync(require.resolve("../js/settings/settings-view.js"), "utf8");
const css = fs.readFileSync(require.resolve("../css/game.css"), "utf8");
const development = fs.readFileSync(require.resolve("../js/development-v2.js"), "utf8");

assert.match(app, /global\.ShopView\.create/);
assert.match(app, /global\.SettingsController\.create/);
assert.doesNotMatch(app, /const developmentCard =/);
assert.match(shopController, /querySelector\("\.shop-back"\)\.onclick = \(\) => renderHome\(\)/);
assert.doesNotMatch(shopController, /addEventListener\("click", render\)/);
assert.match(settingsController, /const selectingEmblem = options\?\.view === "emblems"/);
assert.match(settingsController, /selectingEmblem \? render\(\{ view: "main" \}\) : renderHome\(\)/);
assert.doesNotMatch(shopView, /data-equip-emblem|>SELEZIONA/);
assert.match(settingsController, /const choices = \[\{ emblemId: "default-lightning"/);
assert.match(settingsController, /ShopCatalog\.build\(\)\.filter\(\(item\) => owned\.has\(item\.emblemId\)\)/);
assert.match(development, /ie1: .*ttzfl1b8nbe\.png/);
assert.match(development, /ie1_s2: .*am1r5xc99es\.png/);
assert.match(development, /ie1_s3: .*8kamtdks40c\.png/);
assert.match(development, /ie2: .*radfiq7yd5u\.png/);
const assetUrls = [...development.matchAll(/(?:ie1|ie1_s2|ie1_s3|ie2): "(https:[^"]+)"/g)].map((match) => match[1]);
assert.equal(assetUrls.length, 4);
assert.equal(new Set(assetUrls).size, 4);
assert.match(shopView, /data-cup-season=/);
assert.match(shopView, /cupIcon\(product\.seasonId, "shop-price-cup"\)/);
assert.doesNotMatch(shopView, /data-cup-fallback/);
assert.match(shopView, /TIER_ORDER = \{ base: 0, rare: 1, epic: 2, iconic: 3 \}/);
assert.match(shopView, /TIER_ORDER\[a\.rarity\] - TIER_ORDER\[b\.rarity\]/);
assert.match(shopView, /devMode \? devMarkup\(\) : ""/);
assert.match(shopController, /Math\.max\(state\.coins, 10000\)/);
assert.match(settingsView, /AUTO-FORMAZIONE INTELLIGENTE/);
assert.match(css, /\.shop-product \.btn\{[^}]*background:var\(--yellow\)!important[^}]*background-image:none!important/);
assert.match(css, /\.settings-screen \.settings-panel \.btn-yellow\{[^}]*background:#ffd21f!important[^}]*background-image:none!important/);
console.log("shop-settings-integration-test: extracted ownership, navigation, cup assets and scoped visuals OK");
