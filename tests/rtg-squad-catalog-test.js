"use strict";
const assert=require("assert"),fs=require("fs"),vm=require("vm");
const compact=(player,opts={})=>`<button class="player-card ${opts.extraClass||""}" ${opts.dataAttr||""}><strong>${player.name}</strong>${opts.trailingMarkup||""}</button>`;
const resolver={resolveAtLevel20:(id)=>({playerId:id,name:id,overall:80,level:20,normalizedRole:id.startsWith("d")?"DF":id.startsWith("m")?"MF":id.startsWith("g")?"GK":"FW",position:id.startsWith("d")?"DF":id.startsWith("m")?"MF":id.startsWith("g")?"GK":"FW"})};
const c={globalThis:null,Object,Array,String,Number,Math,Set,Map,JSON};c.globalThis=c;vm.createContext(c);
vm.runInContext(fs.readFileSync("js/road-to-glory/rtg-squad-view-base.js","utf8"),c);
vm.runInContext(fs.readFileSync("js/road-to-glory/rtg-squad-view-catalog-canonical.js","utf8"),c);
const view=c.RoadToGlorySquadView.create({escapeHtml:s=>String(s),playerResolver:resolver,compactPlayerCardMarkup:compact});
assert.strictEqual(typeof view.catalogMarkup,"function");
const lineup=["g1","d1","d2","d3","d4","m1","m2","m3","f1","f2","f3"],bench=["g2","d5","m4","f4"];
const state={activeSeasonId:"ie1",gachaAcquiredPlayerIds:["f9","d9"],squads:{ie1:{formationId:"4-3-3",lineup,bench,activeRoleVariantByPlayerId:{}}}};
const seasonDb={formations:{eleven:[{id:"4-3-3",name:"4-3-3",requirements:{GK:1,DF:4,MF:3,FW:3}}]}};
const model=view.renderModel({state,freeAgentIds:[...lineup,...bench],seasonDb,freeAgentsDb:{players:[]}});
const html=view.markup(model);
assert.match(html,/data-rtg-open-catalog/);
assert.doesNotMatch(html,/rtg-source-badge[^>]*>[\s\S]*?RTG/i);
const catalog=view.catalogMarkup({entries:[{playerId:"f9",source:"RTG",player:resolver.resolveAtLevel20("f9")}],total:1});
assert.match(catalog,/Giocatori RTG/i);
assert.match(catalog,/data-rtg-catalog-player="f9"/);
const quick=view.replacementPickerMarkup({target:{playerId:"d1",player:resolver.resolveAtLevel20("d1")},role:"DF",quickEntries:[{playerId:"d5",source:"Svincolato",player:resolver.resolveAtLevel20("d5")}],entries:[],total:0});
assert.match(quick,/rtg-picker-quick-bench/);
assert.match(quick,/data-rtg-picker-player="d5"/);
console.log("rtg-squad-catalog-test: PASS");
