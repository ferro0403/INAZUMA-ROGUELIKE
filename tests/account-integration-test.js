'use strict';
const assert = require('assert');
const fs = require('fs');
const app = fs.readFileSync('js/app.js', 'utf8');
const ui = fs.readFileSync('js/account-ui.js', 'utf8');
const firebase = fs.readFileSync('js/firebase-account.js', 'utf8');
const html = fs.readFileSync('index.html', 'utf8');

const header = app.slice(app.indexOf('function topbar'), app.indexOf('function navIcon'));
const home = app.slice(app.indexOf('async function renderHome'), app.indexOf('async function selectSeason'));
assert.doesNotMatch(header, /buttonMarkup|data-account-trigger/);
assert.match(header, /<small>OVR<\/small>/);
assert.match(header, /<small>LV<\/small>/);
assert.match(header, /status-pill lives/);
assert.match(header, /hearts\(\)/);
assert.match(home, /buttonMarkup/);
assert.match(home, /data-account-trigger/);
assert.doesNotMatch(home, /home-status-badges|<small>Vite<\/small>|Livello team/);
assert.match(app, /<small>Vite<\/small>/, 'run summaries retain lives');
assert.match(app, /<small>Lv<\/small>/, 'run summaries retain level');
assert.strictEqual((ui.match(/document\.addEventListener\("click", onClick\)/g) || []).length, 1);
assert.match(ui, /data-account-tab/);
assert.match(ui, /function close\(\)/);
assert.match(firebase, /onAuthStateChanged/);
assert.strictEqual((firebase.match(/onAuthStateChanged\(/g) || []).length, 1);
assert.strictEqual((firebase.match(/getDoc\(/g) || []).length, 1);
assert.match(firebase, /publish\(\{[\s\S]*?username: user\.displayName \|\| ""/);
assert.match(firebase, /const profile = await profileState\(user\)/);
assert.doesNotMatch(firebase, /onSnapshot|localStorage|inazuma_roguelike_profile|autosync/i);
assert.match(firebase, /runTransaction/);
assert.match(firebase, /deleteUser\(user\)/);
assert.match(firebase, /sendEmailVerification/);
assert.match(firebase, /sendPasswordResetEmail/);
assert.match(html, /type="module" src="js\/firebase-account\.js/);
assert.ok(html.indexOf('js/firebase-account.js') < html.indexOf('js/season1-config.js'), 'Firebase module starts downloading before game scripts');
assert.strictEqual((html.match(/js\/firebase-account\.js/g) || []).length, 1);
assert.match(ui, /await global\.InazumaAccount\.logout\(\);\s*setBusy\(false\);\s*close\(\);/);
assert.doesNotMatch(ui, /location\.reload|localStorage/);
console.log('account-integration-test: ok');
