"use strict";
const assert=require("assert"),fs=require("fs"),vm=require("vm");
const c={globalThis:null,Object,Array,String,Number,Math,Set,Map,JSON};c.globalThis=c;vm.createContext(c);
vm.runInContext(fs.readFileSync("js/road-to-glory/rtg-match-view.js","utf8"),c);
const view=c.RoadToGloryMatchView.create({escapeHtml:s=>String(s)});
const p=(id,role)=>({playerId:id,name:id,position:role,normalizedRole:role,overall:80});
const lineup=[p("g1","GK"),p("d1","DF"),p("d2","DF"),p("d3","DF"),p("d4","DF"),p("m1","MF"),p("m2","MF"),p("m3","MF"),p("f1","FW"),p("f2","FW"),p("f3","FW")];
const bench=[p("g2","GK"),p("d5","DF"),p("m4","MF"),p("f4","FW")];
let html=view.halftimeMarkup({lineup,bench},{selectedPlayerId:null});
assert.strictEqual((html.match(/data-rtg-half-lineup=/g)||[]).length,11);
assert.strictEqual((html.match(/data-rtg-half-bench=/g)||[]).length,0);
assert.match(html,/Tocca un titolare/i);
html=view.halftimeMarkup({lineup,bench},{selectedPlayerId:"d1"});
assert.match(html,/Cambi compatibili/i);
assert.strictEqual((html.match(/data-rtg-half-bench=/g)||[]).length,1);
assert.match(html,/d5/);
assert.doesNotMatch(html,/data-rtg-half-bench="g2"/);
console.log("rtg-halftime-focused-picker-test: PASS");