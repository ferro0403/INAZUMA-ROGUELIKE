"use strict";
const assert=require("assert"),fs=require("fs"),vm=require("vm");
const c={globalThis:null,Object,Array,String,Number,Math};c.globalThis=c;vm.createContext(c);
vm.runInContext(fs.readFileSync("js/road-to-glory/rtg-ai-policy.js","utf8"),c);
const A=c.RoadToGloryAiPolicy;
function chance(ctx){return A.moveChance({minute:30,period:"second_half",score:{ai:0,user:0},encounterKind:"dribble",remainingUses:2,hasCompatibleMove:true,...ctx});}
assert.strictEqual(chance({hasCompatibleMove:false}),0);
assert.strictEqual(chance({remainingUses:0}),0);
assert.strictEqual(chance({baseProbabilityForAi:80}),35);
assert.strictEqual(chance({baseProbabilityForAi:60}),55);
assert.strictEqual(chance({baseProbabilityForAi:50}),70);
assert.strictEqual(chance({baseProbabilityForAi:35}),82);
assert.strictEqual(chance({baseProbabilityForAi:20}),90);
assert.strictEqual(chance({baseProbabilityForAi:50,minute:75,score:{ai:0,user:0}}),80);
assert.strictEqual(chance({baseProbabilityForAi:50,minute:85,score:{ai:0,user:1}}),90);
assert.strictEqual(chance({baseProbabilityForAi:50,minute:85,score:{ai:0,user:1},encounterKind:"shot"}),95);
assert.strictEqual(chance({baseProbabilityForAi:60,minute:30,remainingUses:1}),50);
const ctx=Object.freeze({minute:40,period:"first_half",score:Object.freeze({ai:0,user:0}),encounterKind:"defense",baseProbabilityForAi:50,remainingUses:2,hasCompatibleMove:true,userChoice:"move"});
const before=JSON.stringify(ctx);
const first=A.chooseMove(ctx,0.2);
const second=A.chooseMove({...ctx,userChoice:"base"},0.2);
assert.strictEqual(first,"move");assert.strictEqual(second,"move");assert.strictEqual(JSON.stringify(ctx),before);
assert.strictEqual(A.chooseMove({...ctx,baseProbabilityForAi:80},0.2),"move");
assert.strictEqual(A.chooseMove({...ctx,baseProbabilityForAi:80},0.5),"normal");
