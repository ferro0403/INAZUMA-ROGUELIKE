"use strict";
const assert=require("assert"),fs=require("fs"),vm=require("vm");
const load=(path,context)=>vm.runInNewContext(fs.readFileSync(path,"utf8"),context,{filename:path});
const context={console};context.globalThis=context;
load("js/road-to-glory/rtg-config.js",context);
load("js/road-to-glory/rtg-route-view.js",context);
const cfg=context.RoadToGloryConfig;
const view=context.RoadToGloryRouteView.create({escapeHtml:String,teamEmblemMarkup:()=>"<em>logo</em>",seasonNumber:()=>2,header:()=>"",tabs:()=>""});
const db=JSON.parse(fs.readFileSync("data/ORION_season_compact.json","utf8"));
const seasonHtml=sid=>{const nodes=Array.from(cfg.buildSeasonNodes(sid));return view.runMarkup({state:{activeSeasonId:sid,currentNodeId:nodes[0].id,tokens:1000,defeatedTeamIds:[],attemptsByNode:{}},nodes,seasonDb:db,seasonConfig:cfg.season(sid)});};
const orion=seasonHtml("orion"),ares=seasonHtml("ie2");
assert(orion.includes('data-rtg-node-id="main:raging_bulls"'));
assert(/left:31%;top:20%[^>]*data-rtg-node-id="main:raging_bulls"/.test(orion),"first Orion boss and path must start below the chapter header");
assert(/left:31%;top:9%[^>]*data-rtg-node-id="main:polestar_academy"/.test(ares),"Ares map remains unchanged");
assert(orion.includes("M 31 20"),"SVG route anchor follows the shifted first boss");
assert.strictEqual((orion.match(/data-rtg-node-id="secondary:/g)||[]).length,12);
const css=fs.readFileSync("css/rtg-theme.css","utf8");
assert(css.includes('.player-detail-hero:has(.player-detail-rtg-role-switch) .player-detail-team'));
assert(css.includes('text-overflow:ellipsis!important'));
assert(css.includes('white-space:nowrap!important'));
assert(fs.readFileSync("js/player/player-view.js","utf8").includes('title="${escapeHtml(teamIdentity.name)}"'));
console.log("RTG QoL: Orion map first boss and SVG spacing, Ares unchanged, full team tooltip and responsive ellipsis PASS");
