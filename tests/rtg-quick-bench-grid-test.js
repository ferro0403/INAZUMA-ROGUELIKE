"use strict";
const assert=require("assert"),fs=require("fs"),vm=require("vm");
const css=fs.readFileSync("css/rtg-theme.css","utf8");
const index=fs.readFileSync("index.html","utf8");
const viewSource=fs.readFileSync("js/road-to-glory/rtg-squad-view-base.js","utf8");
assert(index.includes("css/rtg-theme.css?v=20261010-vending-polish-2"),"live stylesheet must bust mobile cache");
assert(viewSource.includes('class="rtg-picker-quick-strip"'),"quick-bench markup must remain present");
const override=css.slice(css.indexOf("/* RTG Cambia giocatore: four quick-bench cards"));
assert(override.includes(".modal.rtg-squad-picker-modal .rtg-picker-quick-strip{"),"CSS must target actual picker modal");
assert(/grid-template-columns:repeat\(4,minmax\(0,1fr\)\)!important/.test(override),"all 4 bench cards must fit one grid row");
assert(/overflow:visible!important/.test(override),"quick strip must not scroll/crop Legacy badges");
assert(/\.rtg-picker-quick-strip > \[data-rtg-picker-player\]\{[\s\S]*?width:100%!important;[\s\S]*?max-width:100%!important;[\s\S]*?min-width:0!important;/.test(override),"forced legacy 82/88px widths must be defeated");
assert(!/\.rtg-picker-grid\s*\{/.test(override),"full player catalog layout must be unchanged");
const c={globalThis:null,Object,Array,String,Number,Math,Set,Map,JSON};c.globalThis=c;
vm.createContext(c);
vm.runInContext(viewSource,c);
const view=c.RoadToGlorySquadView.create({escapeHtml:s=>String(s)});
const make=(i)=>({cardId:"card"+i,playerId:"card"+i,source:"RTG",player:{cardId:"card"+i,playerId:"card"+i,name:"Player "+i,normalizedRole:["FW","MF","DF","GK"][i],overall:80+i}});
const html=view.replacementPickerMarkup({target:{playerId:"target",player:{name:"Mark Evans"}},allowAnyRole:true,quickEntries:[0,1,2,3].map(make),entries:[]});
const quick=html.match(/<div class="rtg-picker-quick-strip">([\s\S]*?)<\/div><\/section>/);
assert(quick,"all-four rapid strip must be rendered");
assert.strictEqual((quick[1].match(/data-rtg-picker-player="/g)||[]).length,4,"four separate clickable quick cards");
assert(html.includes("qualsiasi ruolo"),"unrestricted role selector must remain active");
console.log("rtg-quick-bench-grid-test: PASS");
