'use strict';
const assert = require('assert');
const fs = require('fs');
const cloud = fs.readFileSync('js/firebase-cloud-save.js', 'utf8');
const ui = fs.readFileSync('js/account-ui.js', 'utf8');
assert.match(cloud, /function hashesMatchManifest/);
assert.match(cloud, /const repaired = metadataFrom/);
assert.match(cloud, /status: "synced", localRevision: manifest\.revision/);
assert.match(cloud, /async function resolveConflictUseLocal/);
assert.match(cloud, /async function resolveConflictUseCloud/);
assert.match(cloud, /state\.status !== "conflict-confirm-local"/);
assert.match(cloud, /state\.status !== "conflict-confirm-cloud"/);
const localResolution = cloud.slice(cloud.indexOf('async function resolveConflictUseLocal'), cloud.indexOf('async function resolveConflictUseCloud'));
assert.doesNotMatch(localResolution, /readDocument|getDoc|onSnapshot/);
assert.match(localResolution, /nextRevision = old\.revision \+ 1/);
assert.match(localResolution, /const changed = core\.SECTOR_NAMES\.filter/);
assert.match(localResolution, /batch\.update[\s\S]*await batch\.commit/);
assert.ok(localResolution.indexOf('writeMetadata(uid, metadata)') > localResolution.indexOf('await batch.commit()'), 'metadata changes only after commit');
assert.match(localResolution, /stale \? "sync-conflict"/);
assert.match(cloud, /restoreCloudSave\(\{ explicitConflict: true \}\)/);
assert.match(ui, /USA QUESTO DISPOSITIVO/);
assert.match(ui, /USA IL SALVATAGGIO CLOUD/);
assert.match(ui, /CONFERMA SOSTITUZIONE CLOUD/);
assert.match(ui, /Il salvataggio locale di questo dispositivo verrà sostituito dalla versione cloud/);
assert.match(ui, /data-cloud-conflict-local-confirm/);
assert.match(ui, /data-cloud-conflict-cloud-confirm/);
assert.doesNotMatch(cloud, /onSnapshot|setInterval|runTransaction/);
console.log('cloud-conflict-resolution-test: ok');
