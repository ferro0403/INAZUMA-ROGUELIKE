'use strict';
const assert = require('assert');
const fs = require('fs');
const app = fs.readFileSync('js/app.js', 'utf8');
const css = fs.readFileSync('css/game.css', 'utf8');
const html = fs.readFileSync('index.html', 'utf8');
const manifest = JSON.parse(fs.readFileSync('manifest.webmanifest', 'utf8'));
const bossHeader = app.slice(app.indexOf('<section class="boss-match-hero panel">'), app.indexOf('<section class="panel boss-match-pitch-panel'));
assert.doesNotMatch(bossHeader, /Preparazione|bossStatusLabel|<em>/i, 'boss header has no preparation badge');
assert.match(html, /class="loading-logo" src="\/assets\/icons\/icon-512\.png"/);
assert.match(css, /\.loading-screen \{[^}]*#fffdf6|\.loading-screen \{[^}]*255,253,246/s);
assert.doesNotMatch(html, /ball-loader|⚽/);
assert.match(html, /rel="apple-touch-icon" sizes="180x180" href="\/assets\/icons\/apple-touch-icon-180\.png"/);
assert.strictEqual((html.match(/rel="apple-touch-icon"/g) || []).length, 1);
assert.match(html, /rel="manifest" href="\/manifest\.webmanifest"/);
assert.strictEqual(manifest.theme_color, '#ffd21f');
assert.strictEqual(manifest.background_color, '#fffdf6');
function pngSize(path) { const b=fs.readFileSync(path); assert.strictEqual(b.toString('hex',0,8),'89504e470d0a1a0a'); return [b.readUInt32BE(16),b.readUInt32BE(20)]; }
for (const [path,size] of [['assets/icons/apple-touch-icon-180.png',180],['assets/icons/icon-192.png',192],['assets/icons/icon-512.png',512],['assets/icons/icon-maskable-512.png',512]]) assert.deepStrictEqual(pngSize(path),[size,size]);
const fiveMatch = app.slice(app.indexOf('function fiveMatchCard'), app.indexOf('function fiveMatchField'));
assert.match(fiveMatch, /compactPlayerCardMarkup\(player/);
assert.match(fiveMatch, /equipmentInFooter: true/);
assert.doesNotMatch(fiveMatch, /fivePlayerEquipmentMarkup/);
