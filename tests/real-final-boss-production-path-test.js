"use strict";
const assert = require("assert");
const { load } = require("./helpers/production-runtime");
const BudgetStorage = require("./helpers/budget-storage");
const ie2 = require("../data/IE2_season_compact.json");
const finalBoss = ie2.bossOrder.at(-1);
assert.equal(finalBoss.teamId, "barcelona_orb");
const run = { runId: "ie2-final-ui", seasonId: "ie2", lives: 2, bossIndex: ie2.bossOrder.length - 1, phase: "match", completedBossIds: ie2.bossOrder.slice(0, -1).map(x => x.teamId), unlockedTeamIds: [], inventory: [], roster: [], lineup: [], bench: [], formationId: "4-3-3", teamIdentity: { name: "Raimon" }, statistics: {}, currentZone: { nodes: [{ id: "barcelona-final", type: "boss" }], path: [], completedNodeIds: [] }, activeMatch: { matchId: "final-match", type: "boss", bossIndex: ie2.bossOrder.length - 1, nodeId: "barcelona-final", state: "playing", simulation: { resolutionApplied: false, score: { user: 2, opponent: 1 } } } };
const storage = new BudgetStorage(2_000_000);
let runtime = load(storage, { run, seasonDb: ie2 });
const flow = runtime.seam;
flow.completeBossMatch("victory");
flow.resolvePendingRunFlow({ clearMatch: true });
while (flow.getRun().postBossFlow?.remainingRewards > 0) flow.advanceBossReward();
flow.continueAfterMatch({ preventDefault() {} });
const transition = flow.finishBossVictoryTransition();
flow.navigateBossVictoryDestination(transition || { destination: "season-complete" });
flow.resumeRunFinalization({ render: false });
const saved = runtime.canonical;
assert(saved.completedBossIds.includes("barcelona_orb"));
assert.equal(saved.bossIndex, ie2.bossOrder.length);
assert.equal(saved.finalization.status, "complete");
assert.equal(runtime.hall.length, 1);
assert.equal(runtime.redeemed.size, 1);
assert.equal(saved.permanentEffectOutbox.filter(x => x.status !== "applied").length, 0);
runtime = runtime.reopen({ seasonDb: ie2 });
assert(runtime.canonical.completedBossIds.includes("barcelona_orb"));
assert.equal(runtime.canonical.bossIndex, ie2.bossOrder.length);
runtime.seam.resumeRunFinalization({ render: false });
runtime = runtime.reopen({ seasonDb: ie2 });
assert.equal(runtime.hall.length, 1); assert.equal(runtime.redeemed.size, 1);
assert.equal(runtime.context.PersistenceRecoveryGuard.isBlocked(), false);
assert.equal([...storage.map.keys()].some(k => k.includes("restoreJournal")), false);
console.log("true final boss app seam: ok");
