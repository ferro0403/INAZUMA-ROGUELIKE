"use strict";
const assert=require("assert"),fs=require("fs"),vm=require("vm");
const c={globalThis:null,Object,Array,String,Number,Math,Set,Map};c.globalThis=c;vm.createContext(c);
vm.runInContext(fs.readFileSync("js/road-to-glory/rtg-encounter-runtime.js","utf8"),c);
const R=c.RoadToGloryEncounterRuntime;
const player={overall:80,attack:90,control:75,speed:70,grit:85,physical:78,stamina:82,defense:60,save:20,element:"Fuoco"};
assert.strictEqual(R.specificAverage(player,"shot"),(90+75+85)/3);
assert.strictEqual(R.baseStrength(player,"shot"),0.5*80+0.5*((90+75+85)/3));
assert.strictEqual(R.moveBonus(50),5);
assert.strictEqual(R.moveBonus(80),8.5);
assert.strictEqual(R.moveBonus(110),12);
const flat=(overall,element="Wind")=>({overall,attack:overall,control:overall,speed:overall,grit:overall,physical:overall,stamina:overall,defense:overall,save:overall,element});
assert.strictEqual(R.probability({actor:flat(80),opponent:flat(80),actorKind:"dribble",opponentKind:"defense"}).probability,50);
assert.strictEqual(R.probability({actor:flat(85),opponent:flat(80),actorKind:"dribble",opponentKind:"defense"}).probability,62.5);
assert.strictEqual(R.probability({actor:flat(90),opponent:flat(80),actorKind:"shot",opponentKind:"save"}).probability,75);
assert.strictEqual(R.probability({actor:flat(99),opponent:flat(1),actorKind:"shot",opponentKind:"save"}).probability,90);
assert.strictEqual(R.probability({actor:flat(1),opponent:flat(99),actorKind:"shot",opponentKind:"save"}).probability,10);
assert.strictEqual(R.elementModifier("Fuoco","Albero"),5);
assert.strictEqual(R.elementModifier("Forest","Fire"),-5);
assert.strictEqual(R.elementModifier("Vento","Montagna"),5);
assert.strictEqual(R.elementModifier("Mountain","Wind"),-5);
const baseEl=R.probability({actor:flat(80,"Fuoco"),opponent:flat(80,"Albero"),actorKind:"dribble",opponentKind:"defense"});
assert.strictEqual(baseEl.probability,55);
const bothGood=R.probability({actor:flat(80,"Fuoco"),opponent:flat(80,"Albero"),actorKind:"dribble",opponentKind:"defense",actorMove:{power:50,element:"Fire"},opponentMove:{power:50,element:"Forest"}});
assert.strictEqual(bothGood.playerElementModifier,5);assert.strictEqual(bothGood.moveElementModifier,5);assert.strictEqual(bothGood.probability,60);
const cancel=R.probability({actor:flat(80,"Fuoco"),opponent:flat(80,"Albero"),actorKind:"dribble",opponentKind:"defense",actorMove:{power:50,element:"Forest"},opponentMove:{power:50,element:"Fire"}});
assert.strictEqual(cancel.playerElementModifier,5);assert.strictEqual(cancel.moveElementModifier,-5);assert.strictEqual(cancel.probability,50);
const oneMove=R.probability({actor:flat(80,"Fuoco"),opponent:flat(80,"Albero"),actorKind:"dribble",opponentKind:"defense",actorMove:{power:50,element:"Fire"}});
assert.strictEqual(oneMove.moveElementModifier,0);
assert.deepStrictEqual(JSON.parse(JSON.stringify(R.compatibleMoveTypes("dribble","defense"))),{actor:"dribble",opponent:"defense"});
assert.deepStrictEqual(JSON.parse(JSON.stringify(R.compatibleMoveTypes("shot","save"))),{actor:"shot",opponent:"save"});
console.log("rtg-encounter-runtime-test: PASS");
