"use strict";
const assert = require("assert");
const fs = require("fs");
const vm = require("vm");
const context = { globalThis: null, Object, Array, Set, Map, JSON, Math };
context.globalThis = context;
vm.createContext(context);
vm.runInContext(fs.readFileSync("js/road-to-glory/rtg-config.js", "utf8"), context);
const { SEASON1, buildSeasonNodes } = context.RoadToGloryConfig;
assert.deepStrictEqual(Array.from(SEASON1.mainTeams), ["occult","wild","brainwashing","otaku","shuriken","farm","kirkwood","royal","zeus","raimon"]);
assert.strictEqual(SEASON1.pullCost, 300);
assert.deepStrictEqual(JSON.parse(JSON.stringify(SEASON1.rarityWeights)), {Normale:40,Buono:27,Forte:18,Elite:10,Mondiale:5,Leggenda:0});
assert.deepStrictEqual(JSON.parse(JSON.stringify(SEASON1.duplicateRefunds)), {Normale:40,Buono:60,Forte:85,Elite:120,Mondiale:160,Leggenda:300});
assert.strictEqual(SEASON1.mainRewards.occult, 210);
assert.strictEqual(SEASON1.mainRewards.raimon, 630);
assert.deepStrictEqual(JSON.parse(JSON.stringify(SEASON1.secondaryRewards)), [{amount:100,weight:70},{amount:110,weight:20},{amount:125,weight:8},{amount:150,weight:2}]);
const nodes = Array.from(buildSeasonNodes("ie1"));
assert.strictEqual(nodes.length, 28);
assert.strictEqual(nodes[0].id, "main:occult");
assert.strictEqual(nodes.at(-1).id, "main:raimon");
assert.strictEqual(nodes.filter(n => n.type === "secondary").length, 18);
const firstSecondary = nodes.find(n => n.type === "secondary");
assert.deepStrictEqual({cap:firstSecondary.userCap,min:firstSecondary.opponentTargetMin,max:firstSecondary.opponentTargetMax},{cap:77,min:73,max:76});
const beforeZeus = nodes.find(n => n.type === "secondary" && n.beforeTeamId === "zeus");
assert.deepStrictEqual({cap:beforeZeus.userCap,min:beforeZeus.opponentTargetMin,max:beforeZeus.opponentTargetMax},{cap:87,min:83,max:86});
assert.deepStrictEqual(nodes.filter(n => n.checkpointAfter).map(n => n.teamId), ["brainwashing","farm","zeus"]);
console.log("rtg-season1-config-test: PASS");
