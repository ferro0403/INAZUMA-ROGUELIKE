"use strict";
const assert = require("assert");
const BudgetStorage = require("./helpers/budget-storage");
const { load } = require("./helpers/production-runtime");

const players = ["GK", "DF", "DF", "DF", "DF", "MF", "MF", "MF", "FW", "FW", "FW"].map((position, index) => ({ playerId: `p${index}`, name: `P${index}`, position, overall: 50, finalOverall: 50, stats: {} }));
const database = { seasonId: "ie1_s3", players, teams: [], formations: { eleven: [] }, bossOrder: [] };
const run = { version: 2, runId: "diagnostic-run", seasonId: "ie1_s3", phase: "match", lives: 2, bossIndex: 0, teamIdentity: { name: "Local" }, roster: players.map(({ playerId }) => ({ playerId, source: "ie1_s3", level: 0 })), lineup: players.map(({ playerId }) => playerId), bench: [], inventory: [], completedBossIds: [], unlockedTeamIds: [], currentZone: { currentNodeId: "start", pendingNodeId: "match", nodes: [] }, activeMatch: { matchId: "diagnostic-match", type: "boss", state: "pre-match", simulation: null } };
const storage = new BudgetStorage(Infinity);
const sessionStorage = new BudgetStorage(Infinity);
const runtime = load(storage, { run, seasonDb: database, contextOverrides: { location: { search: "?dev=1", href: "https://preview.test/?dev=1" }, sessionStorage } });
runtime.context.RoguelikeRules.isProfileAwareRosterEntry = () => false;
runtime.context.SeasonRegistry.player = id => players.find(player => player.playerId === String(id));
runtime.context.MatchSimulator.simulate = ({ seed }) => ({ valid: true, seed, winner: "user", score: { user: 1, opponent: 0 }, timeline: [], probabilities: {}, userStrength: {}, opponentStrength: {} });
const concurrent = runtime.context.RunState.load("ie1_s3", { readOnly: true });
concurrent.bossIndex = 1;
runtime.context.RunState.save(concurrent);
const result = runtime.seam.startMatchSimulation(runtime.seam.getRun().activeMatch);
assert.equal(result.suspended, true);
const entries = runtime.context.__INAZUMA_GAMEPLAY_FAILURE_DIAGNOSTICS__();
assert.equal(entries.length, 1);
assert.equal(entries[0].label, "match-simulation-start");
assert.equal(entries[0].stage, "persistence");
assert.equal(entries[0].error.code, "stale-write");
assert.equal(entries[0].error.stage, "concurrency");
assert.equal(entries[0].seasonId, "ie1_s3");
assert.equal(entries[0].runId, "diagnostic-run");
assert.equal(entries[0].attempt.storageGeneration, 1);
assert.equal(entries[0].canonicalBefore.generation, 2);
assert.equal(entries[0].canonicalAfter.generation, 2);
assert.notEqual(entries[0].attempt.storageCommitId, entries[0].canonicalAfter.commitId);
assert.equal(entries[0].expected.explicitExpectedGeneration, null);
assert.equal(entries[0].errorReportedGeneration, 2);
assert.equal(entries[0].matchAttempt.matchId, "match");
assert.equal(entries[0].matchAttempt.state, "simulating");
assert.equal(entries[0].matchCanonical.state, "pre-match");
assert.equal(entries[0].matchCanonical.matchId, "diagnostic-match");
assert.equal(entries[0].nodeAttempt.currentNodeId, "start");
assert.equal(entries[0].nodeCanonical.pendingNodeId, "match");
assert(entries[0].storage.totalKnownBytes > 0);
assert(entries[0].storage.bytes.primary > 0);
const trace = runtime.context.__INAZUMA_GAMEPLAY_TRACE__();
for (const event of ["startMatchSimulation-enter", "match-preview-ready", "commit-match-mutation-enter", "persist-mutation-enter", "save-attempt", "save-failure"]) assert(trace.some(entry => entry.event === event), event);
assert(sessionStorage.getItem("inazuma.dev.gameplayDiagnostics.v1"));
const exported = runtime.context.__INAZUMA_EXPORT_GAMEPLAY_DIAGNOSTICS__();
assert.equal(typeof exported.then, "function");
runtime.context.__INAZUMA_RESET_GAMEPLAY_DIAGNOSTICS__();
assert.equal(runtime.context.__INAZUMA_GAMEPLAY_FAILURE_DIAGNOSTICS__().length, 0);
console.log("Preview dev diagnostics capture the real gameplay transaction failure context: ok");
