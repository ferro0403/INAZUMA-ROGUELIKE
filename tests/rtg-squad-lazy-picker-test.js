const seasonDb={formations:{eleven:[{id:"4-3-3",name:"4-3-3",requirements:{GK:1,DF:4,MF:3,FW:3}}]}};
const model=view.renderModel({state,freeAgentIds:hugeIds,seasonDb,freeAgentsDb:{players:[]}});
assert.strictEqual(model.lineup.length,11);assert.strictEqual(model.bench.length,4);
assert(resolveCalls<=15,`renderModel resolved ${resolveCalls} players instead of only the active 15`);
const html=view.markup(model);
assert.doesNotMatch(html,/rtg-collection-card-grid/);
assert.doesNotMatch(html,/data-rtg-role-filter/);
assert.strictEqual((html.match(/data-rtg-squad-player=/g)||[]).length,15);
assert.match(html,/Tocca un giocatore/i);

