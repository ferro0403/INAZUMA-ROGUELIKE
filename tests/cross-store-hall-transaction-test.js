const assert = require("assert"), fs = require("fs"), vm = require("vm");
const sandbox = { console, structuredClone }; sandbox.globalThis = sandbox;
vm.runInNewContext(fs.readFileSync("js/permanent-effects.js", "utf8"), sandbox);
const run = { runId: "win", seasonId: "ie1", phase: "finalization", finalization: { status: "pending" }, permanentEffectOutbox: [] };
const snapshot = { runId: "win", seasonId: "ie1", archiveKey: "ie1:win", hallTeamId: "hall_win" };
sandbox.PermanentEffects.enqueueHall(run, snapshot);
const halls = new Map();
const hall = { addChampion(value) { if (!halls.has(value.archiveKey)) halls.set(value.archiveKey, value); return { persisted: true, created: halls.size === 1, team: halls.get(value.archiveKey) }; } };
let markerFails = true;
let result = sandbox.PermanentEffects.drain(run, { apis: { HallOfFameStorage: hall }, save() { if (markerFails) throw Error("marker"); } });
assert(result.error); assert.strictEqual(halls.size, 1);
assert.strictEqual(run.permanentEffectOutbox[0].status, "pending");
assert.strictEqual(run.permanentEffectOutbox[0].appliedAt, null);
assert.strictEqual(run.finalization.status, "pending");
assert.strictEqual(Object.hasOwn(run, "hallTeamId"), false);
markerFails = false;
result = sandbox.PermanentEffects.drain(run, { apis: { HallOfFameStorage: hall }, save() {} });
assert.ifError(result.error); assert.strictEqual(halls.size, 1);
assert.strictEqual(run.permanentEffectOutbox[0].status, "applied");
assert.strictEqual(run.finalization.status, "hall-written"); assert.strictEqual(run.hallTeamId, "hall_win");
const readOnly = JSON.parse(JSON.stringify(run)); readOnly.permanentEffectOutbox[0].status = "pending";
sandbox.PermanentEffects.drain(readOnly, { readOnly: true, apis: { HallOfFameStorage: { addChampion() { throw Error("write"); } } }, save() { throw Error("save"); } });
assert.strictEqual(readOnly.permanentEffectOutbox[0].status, "pending");
console.log("cross-store hall transaction tests passed");
