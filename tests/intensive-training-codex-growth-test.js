"use strict";
const assert=require("assert"), progression=require("../js/roguelike_progression.js");
const ratings={attack:1,physical:10,stamina:6,control:7,defense:9,speed:6,grit:7,save:1};
const hauser={playerId:"hauser",position:"DF",finalOverall:84,maxLevel:20,category:"Elite",ratings};
const database={compactFormat:{levelMax:20,statOrder:Object.keys(ratings)}};
const before=progression.getPlayerAtLevel(hauser,0,database);
const first=progression.planCodexTrainingGrowth(hauser,{},3);
assert.deepStrictEqual(first.ratings,progression.findBestCodexGrowthProfile({role:"DF",originalRatings:ratings,currentRatings:ratings,targetOverall:87}),"training shares Development growth core");
assert.strictEqual(first.codexDeltas.physical,undefined,"canonical Physical 10 is capped");
assert(Object.keys(first.codexDeltas).length>0,"another canonical stat grows");
const application={amount:3,appliedLevel:0,codexDeltas:first.codexDeltas};
const options={potentialBoost:3,currentOverallBoost:3,potentialBoostApplications:[application]};
const after=progression.getPlayerAtLevel(hauser,0,database,options);
assert.strictEqual(after.overall,before.overall+3); assert.strictEqual(after.potential,before.potential+3);
assert.strictEqual(after.stats.physical,before.stats.physical,"Hauser Physical does not increase");
assert(Object.keys(first.codexDeltas).some((stat)=>after.stats[stat]>before.stats[stat]));
const second=progression.planCodexTrainingGrowth(hauser,options,3);
assert.deepStrictEqual(second.currentRatings,first.ratings,"second application starts from first temporary profile");
const twice={potentialBoost:6,currentOverallBoost:6,potentialBoostApplications:[application,{amount:3,appliedLevel:0,codexDeltas:second.codexDeltas}]};
const normalized1=progression.normalizePotentialBoostApplications(JSON.parse(JSON.stringify(twice)),15);
const normalized2=progression.normalizePotentialBoostApplications({potentialBoost:6,potentialBoostApplications:normalized1},15);
assert.deepStrictEqual(normalized2,normalized1,"reload/normalize is idempotent");
assert.strictEqual(progression.getPlayerAtLevel(hauser,0,database,twice).overall,before.overall+6);
console.log("intensive-training-codex-growth-test: Hauser cap, multiple uses and reload OK");
